#!/bin/bash
# scripts/lib/standards-lists.sh — Sourceable library that renders the
# enumerable sections of agent configs (standards file lists, language-detection
# maps) from the standards/ tree, and splices them into files between sentinel
# comments.
#
# The standards/ tree is the manifest. A file is a "standard" when it lives in
# one of the category directories and follows the prefix naming scheme
# (architecture/arch-NN_*.md, languages/lang-NN_*.md, process/proc-NN_*.md,
# security/sec-NN_*.md), plus the canonical shared/core-standards.md. Nothing
# else (READMEs, schema docs, content blocks) is ever enumerated.
#
# Optional enrichment lives in standards/catalog.tsv (path, description,
# language triggers). A file with no catalog row still appears in every list;
# its description falls back to the document's H1 title.
#
# Generated regions are delimited by exact sentinel lines:
#   <!-- BEGIN GENERATED: <region-id> -->
#   ...everything here is replaced on every run...
#   <!-- END GENERATED: <region-id> -->
#
# Region ids:
#   standards-list      — grouped list of every standards document
#   language-detection  — "<triggers> → <path>" map for the language standards
#
# Source this file; do not execute it directly. bash 3.2 compatible.
#
# Usage:
#   source "$(dirname "${BASH_SOURCE[0]}")/lib/standards-lists.sh"
#   render_region standards-list standards/ "standards/"
#   splice_generated_regions in.md out.md standards/ "standards/"

STANDARDS_LIST_CATEGORIES="architecture languages process security"
STANDARDS_CATALOG_FILE="catalog.tsv"
GENERATED_BEGIN_PREFIX="<!-- BEGIN GENERATED: "
GENERATED_END_PREFIX="<!-- END GENERATED: "
GENERATED_SUFFIX=" -->"
GENERATED_NOTICE='<!-- Generated by scripts/generate-standards-lists.sh from the standards/ tree. Do not edit by hand; run `make generate-standards-lists`. -->'

# ---------------------------------------------------------------------------
# Category metadata (bash 3 compatible — no associative arrays)
# ---------------------------------------------------------------------------

# standards_category_label <category> — human heading for a category.
standards_category_label() {
    case "$1" in
        architecture) echo "Architecture Standards" ;;
        languages)    echo "Language Standards" ;;
        process)      echo "Process Standards" ;;
        security)     echo "Security Standards" ;;
        shared)       echo "Shared Standards" ;;
        *)            echo "$1" ;;
    esac
}

# standards_category_prefix <category> — filename prefix for a category.
standards_category_prefix() {
    case "$1" in
        architecture) echo "arch" ;;
        languages)    echo "lang" ;;
        process)      echo "proc" ;;
        security)     echo "sec" ;;
        *)            echo "" ;;
    esac
}

# ---------------------------------------------------------------------------
# list_standards_files <standards_dir> [category]
#
# Prints one relative path per line (e.g. "languages/lang-01_python_standards.md"),
# category by category in canonical order, sorted within each category. The
# pseudo-category "shared" yields shared/core-standards.md when it exists.
# ---------------------------------------------------------------------------
list_standards_files() {
    local dir="$1"
    local only="${2:-}"
    local cat prefix f

    for cat in $STANDARDS_LIST_CATEGORIES shared; do
        if [ -n "$only" ] && [ "$only" != "$cat" ]; then
            continue
        fi
        if [ "$cat" = "shared" ]; then
            if [ -f "$dir/shared/core-standards.md" ]; then
                echo "shared/core-standards.md"
            fi
            continue
        fi
        prefix=$(standards_category_prefix "$cat")
        [ -d "$dir/$cat" ] || continue
        for f in "$dir/$cat/$prefix"-[0-9]*_*.md; do
            [ -f "$f" ] || continue
            echo "$cat/$(basename "$f")"
        done | LC_ALL=C sort
    done
}

# ---------------------------------------------------------------------------
# Metadata lookups
# ---------------------------------------------------------------------------

# standards_file_title <file> — first H1, minus any "Document N:" prefix.
standards_file_title() {
    local title
    title=$(grep -m1 '^# ' "$1" 2>/dev/null \
        | sed -e 's/^# //' -e 's/^Document [0-9][0-9]*: *//' -e 's/[[:space:]]*$//')
    if [ -z "$title" ]; then
        title=$(basename "$1" .md)
    fi
    printf '%s\n' "$title"
}

# standards_catalog_field <standards_dir> <relpath> <column>
# Prints column <column> (1-based) of the catalog row for <relpath>, or nothing.
standards_catalog_field() {
    local catalog="$1/$STANDARDS_CATALOG_FILE"
    [ -f "$catalog" ] || return 0
    awk -F'\t' -v p="$2" -v n="$3" '$0 !~ /^#/ && $1 == p { print $n; exit }' "$catalog"
}

# standards_catalog_paths <standards_dir> — every path the catalog mentions.
standards_catalog_paths() {
    local catalog="$1/$STANDARDS_CATALOG_FILE"
    [ -f "$catalog" ] || return 0
    awk -F'\t' '$0 !~ /^#/ && NF > 0 && $1 != "" { print $1 }' "$catalog"
}

# standards_description <standards_dir> <relpath> — catalog description or H1.
standards_description() {
    local desc
    desc=$(standards_catalog_field "$1" "$2" 2)
    if [ -z "$desc" ]; then
        desc=$(standards_file_title "$1/$2")
    fi
    printf '%s\n' "$desc"
}

# standards_language_name <standards_dir> <relpath> — "Python Standards" → "Python".
standards_language_name() {
    local title
    title=$(standards_file_title "$1/$2")
    printf '%s\n' "${title% Standards}"
}

# standards_language_triggers <standards_dir> <relpath>
# Catalog triggers column (e.g. "`.py` files"), or "<Language> source files".
standards_language_triggers() {
    local triggers
    triggers=$(standards_catalog_field "$1" "$2" 3)
    if [ -z "$triggers" ]; then
        triggers="$(standards_language_name "$1" "$2") source files"
    fi
    printf '%s\n' "$triggers"
}

# ---------------------------------------------------------------------------
# Renderers — each prints a complete region body (everything between the
# BEGIN and END sentinels), starting with the generated-content notice and
# ending with a blank line so the END sentinel never abuts a list.
# ---------------------------------------------------------------------------

# render_standards_list <standards_dir> <path_prefix>
render_standards_list() {
    local dir="$1"
    local prefix="$2"
    local cat rel

    printf '%s\n' "$GENERATED_NOTICE"
    for cat in $STANDARDS_LIST_CATEGORIES shared; do
        local files
        files=$(list_standards_files "$dir" "$cat")
        [ -n "$files" ] || continue
        printf '\n**%s:**\n\n' "$(standards_category_label "$cat")"
        printf '%s\n' "$files" | while IFS= read -r rel; do
            printf -- '- `%s%s` — %s\n' "$prefix" "$rel" "$(standards_description "$dir" "$rel")"
        done
    done
    printf '\n'
}

# render_language_detection <standards_dir> <path_prefix>
render_language_detection() {
    local dir="$1"
    local prefix="$2"
    local rel

    printf '%s\n\n' "$GENERATED_NOTICE"
    list_standards_files "$dir" languages | while IFS= read -r rel; do
        printf -- '- %s → `%s%s`\n' "$(standards_language_triggers "$dir" "$rel")" "$prefix" "$rel"
    done
    printf '\n'
}

# render_region <region_id> <standards_dir> <path_prefix>
# Returns 1 (with a message on stderr) for an unknown region id.
render_region() {
    case "$1" in
        standards-list)     render_standards_list "$2" "$3" ;;
        language-detection) render_language_detection "$2" "$3" ;;
        *)
            echo "ERROR: unknown generated region id '$1' (known: standards-list, language-detection)" >&2
            return 1
            ;;
    esac
}

# ---------------------------------------------------------------------------
# splice_generated_regions <input> <output> <standards_dir> <path_prefix>
#
# Copies <input> to <output>, replacing the body of every generated region with
# freshly rendered content. Text outside regions is preserved byte-for-byte.
# Returns 1 on an unknown region id, a nested BEGIN, or an unterminated region;
# the caller decides what to do with the (partial) output in that case.
# ---------------------------------------------------------------------------
splice_generated_regions() {
    local input="$1"
    local output="$2"
    local dir="$3"
    local prefix="$4"
    local line id
    local in_region=""

    : > "$output"
    while IFS= read -r line || [ -n "$line" ]; do
        if [ -n "$in_region" ]; then
            case "$line" in
                "${GENERATED_END_PREFIX}${in_region}${GENERATED_SUFFIX}")
                    printf '%s\n' "$line" >> "$output"
                    in_region=""
                    ;;
                "${GENERATED_BEGIN_PREFIX}"*)
                    echo "ERROR: nested BEGIN GENERATED inside region '$in_region' in $input" >&2
                    return 1
                    ;;
            esac
            continue
        fi

        printf '%s\n' "$line" >> "$output"
        case "$line" in
            "${GENERATED_BEGIN_PREFIX}"*"${GENERATED_SUFFIX}")
                id="${line#"$GENERATED_BEGIN_PREFIX"}"
                id="${id%"$GENERATED_SUFFIX"}"
                if ! render_region "$id" "$dir" "$prefix" >> "$output"; then
                    echo "ERROR: cannot render region '$id' in $input" >&2
                    return 1
                fi
                in_region="$id"
                ;;
        esac
    done < "$input"

    if [ -n "$in_region" ]; then
        echo "ERROR: unterminated generated region '$in_region' in $input (missing ${GENERATED_END_PREFIX}${in_region}${GENERATED_SUFFIX})" >&2
        return 1
    fi
    return 0
}

# file_has_generated_regions <file> — true when <file> carries a BEGIN sentinel.
file_has_generated_regions() {
    grep -qF -- "$GENERATED_BEGIN_PREFIX" "$1" 2>/dev/null
}

# file_has_region <file> <region_id>
file_has_region() {
    grep -qF -- "${GENERATED_BEGIN_PREFIX}$2${GENERATED_SUFFIX}" "$1" 2>/dev/null
}
