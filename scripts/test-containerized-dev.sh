#!/bin/bash
# Functional tests for the containerized agent-dev starter kit's egress layer
# (arch-09 §4, #157): templates/containerized-dev/scripts/setup-proxy.sh.example,
# proxy/egress-entrypoint.sh, and the contract the compose/proxy templates must
# keep (internal network, egress sidecar, deny-by-default filter).
#
# Docker is NOT required: each test copies the templates into a temp "consumer
# project", runs the scripts with a stub tinyproxy on PATH, and asserts outcomes.
# The live deny-path check (an actual blocked request) is the kit README's
# Definition of Done and is run against a real compose stack, not here.
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
KIT="$REPO_ROOT/templates/containerized-dev"
SETUP_PROXY="$KIT/scripts/setup-proxy.sh.example"
ENTRYPOINT="$KIT/proxy/egress-entrypoint.sh"
TINYPROXY_CONF="$KIT/proxy/tinyproxy.conf"
COMPOSE="$KIT/docker-compose.dev.yml.example"
GLOBAL_LIST="$KIT/network/global-whitelist.txt"

RED='\033[0;31m'; GREEN='\033[0;32m'; BLUE='\033[0;34m'; NC='\033[0m'
PASS=0; FAIL=0

TMP_BASE="$(mktemp -d "${TMPDIR:-/tmp}/test-containerized-dev.XXXXXX")"
trap 'rm -rf "$TMP_BASE"' EXIT

pass() { echo -e "${GREEN}✓${NC}"; PASS=$((PASS + 1)); }
fail() { echo -e "${RED}✗${NC}"; echo "  Error: $1"; FAIL=$((FAIL + 1)); }

# make_project <name> → prints a consumer-project dir with the kit's scripts and
# proxy/ copied in, the way the README's Install section does.
make_project() {
    local dir="$TMP_BASE/$1"
    mkdir -p "$dir/scripts" "$dir/proxy"
    cp "$SETUP_PROXY" "$dir/scripts/setup-proxy.sh"
    chmod +x "$dir/scripts/setup-proxy.sh"
    cp "$KIT/proxy/project-whitelist.txt" "$dir/proxy/project-whitelist.txt"
    echo "$dir"
}

# entries <file> → the file's non-comment, non-blank lines.
entries() { sed -e 's/#.*//' -e 's/[[:space:]]//g' "$1" | grep -v '^$'; }

# Stub tinyproxy so the entrypoint's final exec is observable without Docker.
STUB_BIN="$TMP_BASE/bin"
mkdir -p "$STUB_BIN"
printf '#!/bin/sh\nprintf "stub-tinyproxy %%s\\n" "$*"\n' > "$STUB_BIN/tinyproxy"
chmod +x "$STUB_BIN/tinyproxy"

echo -e "${BLUE}Testing containerized-dev egress layer (setup-proxy.sh + egress sidecar)${NC}"
echo ""

# ---------- setup-proxy.sh ----------

# Test 1: combines global + project lists, de-duplicated, comments stripped
echo -n "Test 1:  setup-proxy — combines both layers, de-duplicates, drops comments... "
dir="$(make_project t1)"
printf '# project layer\napi.github.com\n\ninternal.example.com   # trailing comment\n' > "$dir/proxy/project-whitelist.txt"
out="$(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh 2>&1)"; rc=$?
list="$dir/proxy/allowlist.generated.txt"
if [ "$rc" -eq 0 ] && [ -f "$list" ] \
    && [ "$(entries "$list" | grep -c '^api\.github\.com$')" -eq 1 ] \
    && entries "$list" | grep -q '^internal\.example\.com$' \
    && entries "$list" | grep -q '^registry\.npmjs\.org$' \
    && ! entries "$list" | grep -q 'comment'; then
    pass
else
    fail "rc=$rc; output: $out; list: $(cat "$list" 2>/dev/null)"
fi

# Test 2: generated file carries the GENERATED marker and both source paths
echo -n "Test 2:  setup-proxy — output is marked GENERATED and names its sources... "
if grep -q '^# GENERATED by scripts/setup-proxy.sh' "$list" \
    && grep -q "^#   $GLOBAL_LIST" "$list" \
    && grep -q '^#   proxy/project-whitelist.txt' "$list"; then
    pass
else
    fail "header missing: $(head -3 "$list")"
fi

# Test 3: wildcard subdomain entries pass validation; mixed case is normalised
echo -n "Test 3:  setup-proxy — accepts '*.domain' wildcards, lowercases mixed-case hosts... "
dir="$(make_project t3)"
printf '*.githubusercontent.com\nAPI.OpenAI.com\n' > "$dir/proxy/project-whitelist.txt"
out="$(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh 2>&1)"; rc=$?
list="$dir/proxy/allowlist.generated.txt"
if [ "$rc" -eq 0 ] && entries "$list" | grep -q '^\*\.githubusercontent\.com$' \
    && entries "$list" | grep -q '^api\.openai\.com$' \
    && ! grep -q 'OpenAI' "$list"; then
    pass
else
    fail "rc=$rc; output: $out; list: $(cat "$list" 2>/dev/null)"
fi

# Test 3b: single-label hosts and single-label wildcards are not hostnames to allow
echo -n "Test 3b: setup-proxy — rejects single-label hosts and '*.tld' wildcards... "
dir="$(make_project t3b)"
printf 'single-label-host\n*.com\n?*\n*.*\nok.example.com\n' > "$dir/proxy/project-whitelist.txt"
out="$(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh 2>&1)"; rc=$?
if [ "$rc" -eq 2 ] && [ ! -f "$dir/proxy/allowlist.generated.txt" ] \
    && echo "$out" | grep -q '^  single-label-host$' && echo "$out" | grep -q '^  \*\.com$' \
    && echo "$out" | grep -q '^  ?\*$' && echo "$out" | grep -q '^  \*\.\*$' \
    && ! echo "$out" | grep -q '^  ok.example.com$'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 3c: the generated artifact is world-readable regardless of the caller's umask
echo -n "Test 3c: setup-proxy — generated allow-list is mode 0644 even under umask 077... "
dir="$(make_project t3c)"
printf 'api.github.com\n' > "$dir/proxy/project-whitelist.txt"
(cd "$dir" && umask 077 && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh >/dev/null 2>&1)
mode="$(stat -f '%Lp' "$dir/proxy/allowlist.generated.txt" 2>/dev/null || stat -c '%a' "$dir/proxy/allowlist.generated.txt" 2>/dev/null)"
if [ "$mode" = "644" ]; then
    pass
else
    fail "mode=$mode (expected 644)"
fi

# Test 4: a bare '*' is rejected and nothing is written
echo -n "Test 4:  setup-proxy — rejects a bare '*' (catch-all) and writes nothing... "
dir="$(make_project t4)"
printf 'api.github.com\n*\n' > "$dir/proxy/project-whitelist.txt"
out="$(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh 2>&1)"; rc=$?
if [ "$rc" -eq 2 ] && [ ! -f "$dir/proxy/allowlist.generated.txt" ] && [ ! -f "$dir/.env" ] \
    && echo "$out" | grep -q 'Invalid allow-list entries' && echo "$out" | grep -q '^  \*$'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 5: URLs and paths are rejected (they would not be hostnames to the proxy)
echo -n "Test 5:  setup-proxy — rejects URLs and paths in a source list... "
dir="$(make_project t5)"
printf 'https://evil.example.com\nexample.com/path\nok.example.com\n' > "$dir/proxy/project-whitelist.txt"
out="$(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh 2>&1)"; rc=$?
if [ "$rc" -eq 2 ] && [ ! -f "$dir/proxy/allowlist.generated.txt" ] \
    && echo "$out" | grep -q 'https://evil.example.com' && echo "$out" | grep -q 'example.com/path' \
    && ! echo "$out" | grep -q '^  ok.example.com$'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 6: an empty combined list is refused
echo -n "Test 6:  setup-proxy — refuses an empty combined allow-list... "
dir="$(make_project t6)"
printf '# nothing here\n' > "$dir/proxy/project-whitelist.txt"
printf '# nor here\n' > "$dir/empty-global.txt"
out="$(cd "$dir" && GLOBAL_WHITELIST="$dir/empty-global.txt" ./scripts/setup-proxy.sh 2>&1)"; rc=$?
if [ "$rc" -eq 1 ] && [ ! -f "$dir/proxy/allowlist.generated.txt" ] \
    && echo "$out" | grep -q 'EMPTY'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 7: .env gets the managed keys, keeps other lines, and stays idempotent
echo -n "Test 7:  setup-proxy — .env: managed keys written, others preserved, idempotent... "
dir="$(make_project t7)"
printf 'api.github.com\n' > "$dir/proxy/project-whitelist.txt"
printf 'HOST_UID=1000\nCUSTOM=keep-me\nNO_PROXY=stale\n' > "$dir/.env"
(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh >/dev/null 2>&1 \
           && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh >/dev/null 2>&1)
env_file="$dir/.env"
if grep -q '^HOST_UID=1000$' "$env_file" && grep -q '^CUSTOM=keep-me$' "$env_file" \
    && [ "$(grep -c '^EGRESS_PROXY=http://egress:3128$' "$env_file")" -eq 1 ] \
    && [ "$(grep -c '^EGRESS_PROXY_HOST=egress$' "$env_file")" -eq 1 ] \
    && [ "$(grep -c '^EGRESS_PROXY_PORT=3128$' "$env_file")" -eq 1 ] \
    && [ "$(grep -c '^NO_PROXY=' "$env_file")" -eq 1 ] \
    && grep -q '^NO_PROXY=localhost,127.0.0.1,::1$' "$env_file"; then
    pass
else
    fail ".env content: $(cat "$env_file")"
fi

# Test 8: a custom EGRESS_PROXY URL is split into host and port for the SSH tunnel
echo -n "Test 8:  setup-proxy — derives EGRESS_PROXY_HOST/PORT from a custom proxy URL... "
dir="$(make_project t8)"
printf 'api.github.com\n' > "$dir/proxy/project-whitelist.txt"
(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" EGRESS_PROXY="http://gateway.corp.example:8080/" \
    NO_PROXY_BYPASS="localhost,127.0.0.1,::1,db" ./scripts/setup-proxy.sh >/dev/null 2>&1)
env_file="$dir/.env"
if grep -q '^EGRESS_PROXY=http://gateway.corp.example:8080/$' "$env_file" \
    && grep -q '^EGRESS_PROXY_HOST=gateway.corp.example$' "$env_file" \
    && grep -q '^EGRESS_PROXY_PORT=8080$' "$env_file" \
    && grep -q '^NO_PROXY=localhost,127.0.0.1,::1,db$' "$env_file"; then
    pass
else
    fail ".env content: $(cat "$env_file")"
fi

# Test 9: a proxy URL without a port falls back to 3128
echo -n "Test 9:  setup-proxy — proxy URL without a port defaults EGRESS_PROXY_PORT to 3128... "
dir="$(make_project t9)"
printf 'api.github.com\n' > "$dir/proxy/project-whitelist.txt"
(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" EGRESS_PROXY="http://egress" ./scripts/setup-proxy.sh >/dev/null 2>&1)
if grep -q '^EGRESS_PROXY_HOST=egress$' "$dir/.env" && grep -q '^EGRESS_PROXY_PORT=3128$' "$dir/.env"; then
    pass
else
    fail ".env content: $(cat "$dir/.env")"
fi

# Test 10: the shipped global whitelist itself passes validation
echo -n "Test 10: setup-proxy — the shipped global + project whitelists validate cleanly... "
dir="$(make_project t10)"
out="$(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh 2>&1)"; rc=$?
if [ "$rc" -eq 0 ] && [ "$(entries "$dir/proxy/allowlist.generated.txt" | wc -l | tr -d ' ')" -ge 10 ]; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# ---------- egress-entrypoint.sh (fail-closed sidecar start) ----------

run_entrypoint() {
    # run_entrypoint <conf> <filter> → runs the entrypoint with the stub tinyproxy
    PATH="$STUB_BIN:$PATH" TINYPROXY_CONF="$1" TINYPROXY_FILTER="$2" sh "$ENTRYPOINT" 2>&1
}

# Test 11: a valid allow-list starts tinyproxy in the foreground with the config
echo -n "Test 11: egress-entrypoint — valid allow-list execs tinyproxy -d with the config... "
d="$TMP_BASE/ep11"; mkdir -p "$d"
printf '# header\napi.github.com\n\n*.example.com\n' > "$d/filter"
out="$(run_entrypoint "$TINYPROXY_CONF" "$d/filter")"; rc=$?
if [ "$rc" -eq 0 ] && echo "$out" | grep -q '2 allow-list entries loaded' \
    && echo "$out" | grep -q "^stub-tinyproxy -d -c $TINYPROXY_CONF\$"; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 12: missing allow-list (Docker mounts a directory) → refuses to start
echo -n "Test 12: egress-entrypoint — missing allow-list (directory at mount point) refuses to start... "
d="$TMP_BASE/ep12"; mkdir -p "$d/filter"
out="$(run_entrypoint "$TINYPROXY_CONF" "$d/filter")"; rc=$?
if [ "$rc" -ne 0 ] && echo "$out" | grep -q 'allow-list not found' \
    && echo "$out" | grep -q 'setup-proxy.sh' && ! echo "$out" | grep -q 'stub-tinyproxy'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 13: empty allow-list (comments only) → refuses to start
echo -n "Test 13: egress-entrypoint — comments-only allow-list refuses to start... "
d="$TMP_BASE/ep13"; mkdir -p "$d"
printf '# GENERATED\n# nothing\n\n' > "$d/filter"
out="$(run_entrypoint "$TINYPROXY_CONF" "$d/filter")"; rc=$?
if [ "$rc" -ne 0 ] && echo "$out" | grep -q 'has no entries' && ! echo "$out" | grep -q 'stub-tinyproxy'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 14: a bare '*' in the allow-list → refuses to start
echo -n "Test 14: egress-entrypoint — catch-all '*' entry refuses to start... "
d="$TMP_BASE/ep14"; mkdir -p "$d"
printf 'api.github.com\n*\n' > "$d/filter"
out="$(run_entrypoint "$TINYPROXY_CONF" "$d/filter")"; rc=$?
if [ "$rc" -ne 0 ] && echo "$out" | grep -q '^egress:   \*$' && echo "$out" | grep -q "bare '\*'" \
    && ! echo "$out" | grep -q 'stub-tinyproxy'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 14b: every other over-broad or malformed entry is refused too, and all are reported
echo -n "Test 14b: egress-entrypoint — '?*', '*.*', '*.com', URLs and upper case refuse to start... "
d="$TMP_BASE/ep14b"; mkdir -p "$d"
printf 'api.github.com\n?*\n*.*\n*.com\nhttps://evil.example.com\nAPI.GITHUB.COM\nsingle\n' > "$d/filter"
out="$(run_entrypoint "$TINYPROXY_CONF" "$d/filter")"; rc=$?
if [ "$rc" -ne 0 ] && ! echo "$out" | grep -q 'stub-tinyproxy' \
    && echo "$out" | grep -q '^egress:   ?\*$' \
    && echo "$out" | grep -q '^egress:   \*\.\*$' \
    && echo "$out" | grep -q '^egress:   \*\.com$' \
    && echo "$out" | grep -q '^egress:   https://evil.example.com$' \
    && echo "$out" | grep -q '^egress:   API.GITHUB.COM$' \
    && echo "$out" | grep -q '^egress:   single$' \
    && ! echo "$out" | grep -q '^egress:   api.github.com$'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 14c: the shipped whitelists, generated by setup-proxy.sh, satisfy the entrypoint
echo -n "Test 14c: egress-entrypoint — accepts the allow-list setup-proxy.sh generates from the shipped lists... "
dir="$(make_project ep14c)"
(cd "$dir" && GLOBAL_WHITELIST="$GLOBAL_LIST" ./scripts/setup-proxy.sh >/dev/null 2>&1)
out="$(run_entrypoint "$TINYPROXY_CONF" "$dir/proxy/allowlist.generated.txt")"; rc=$?
if [ "$rc" -eq 0 ] && echo "$out" | grep -q 'allow-list entries loaded' && echo "$out" | grep -q '^stub-tinyproxy -d -c'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 15: missing config → refuses to start
echo -n "Test 15: egress-entrypoint — missing tinyproxy.conf refuses to start... "
d="$TMP_BASE/ep15"; mkdir -p "$d"
printf 'api.github.com\n' > "$d/filter"
out="$(run_entrypoint "$d/no-such.conf" "$d/filter")"; rc=$?
if [ "$rc" -ne 0 ] && echo "$out" | grep -q 'config not found' && ! echo "$out" | grep -q 'stub-tinyproxy'; then
    pass
else
    fail "rc=$rc; output: $out"
fi

# Test 15b: a config that is not deny-by-default → refuses to start (fail closed on the config too)
echo -n "Test 15b: egress-entrypoint — config without FilterDefaultDeny Yes refuses to start... "
d="$TMP_BASE/ep15b"; mkdir -p "$d"
printf 'api.github.com\n' > "$d/filter"
grep -v '^FilterDefaultDeny' "$TINYPROXY_CONF" > "$d/open.conf"
out="$(run_entrypoint "$d/open.conf" "$d/filter")"; rc=$?
sed 's/^FilterDefaultDeny Yes$/FilterDefaultDeny No/' "$TINYPROXY_CONF" > "$d/no.conf"
out2="$(run_entrypoint "$d/no.conf" "$d/filter")"; rc2=$?
if [ "$rc" -ne 0 ] && echo "$out" | grep -q "missing the required directive 'FilterDefaultDeny Yes'" \
    && [ "$rc2" -ne 0 ] && echo "$out2" | grep -q "missing the required directive 'FilterDefaultDeny Yes'" \
    && ! echo "$out$out2" | grep -q 'stub-tinyproxy'; then
    pass
else
    fail "rc=$rc rc2=$rc2; output: $out // $out2"
fi

# Test 15c: a config re-pointed at another filter file, or chained to an upstream proxy → refuses to start
echo -n "Test 15c: egress-entrypoint — Filter path override, second Filter or Upstream refuses to start... "
d="$TMP_BASE/ep15c"; mkdir -p "$d"
printf 'api.github.com\n' > "$d/filter"
sed 's|^Filter "/etc/tinyproxy/filter"$|Filter "/tmp/other"|' "$TINYPROXY_CONF" > "$d/repointed.conf"
out1="$(run_entrypoint "$d/repointed.conf" "$d/filter")"; rc1=$?
{ cat "$TINYPROXY_CONF"; printf 'Filter "/tmp/other"\n'; } > "$d/twofilters.conf"
out2="$(run_entrypoint "$d/twofilters.conf" "$d/filter")"; rc2=$?
{ cat "$TINYPROXY_CONF"; printf 'Upstream http corp-proxy.example:8080\n'; } > "$d/upstream.conf"
out3="$(run_entrypoint "$d/upstream.conf" "$d/filter")"; rc3=$?
if [ "$rc1" -ne 0 ] && echo "$out1" | grep -q "missing the required directive 'Filter \"/etc/tinyproxy/filter\"'" \
    && [ "$rc2" -ne 0 ] && echo "$out2" | grep -q 'exactly one Filter directive' \
    && [ "$rc3" -ne 0 ] && echo "$out3" | grep -q 'route around the allow-list: Upstream' \
    && ! echo "$out1$out2$out3" | grep -q 'stub-tinyproxy'; then
    pass
else
    fail "rc=$rc1/$rc2/$rc3; output: $out1 // $out2 // $out3"
fi

# ---------- template contract (what the compose + proxy config must keep) ----------

# Test 16: tinyproxy.conf is deny-by-default with whole-host matching
echo -n "Test 16: tinyproxy.conf — deny by default, fnmatch host filter, no trailing comments... "
if grep -q '^FilterDefaultDeny Yes$' "$TINYPROXY_CONF" \
    && grep -q '^FilterType fnmatch$' "$TINYPROXY_CONF" \
    && grep -q '^FilterURLs Off$' "$TINYPROXY_CONF" \
    && grep -q '^Filter "/etc/tinyproxy/filter"$' "$TINYPROXY_CONF" \
    && ! grep -q '^FilterCaseSensitive' "$TINYPROXY_CONF" \
    && ! grep -E '^[A-Za-z]+ .*#' "$TINYPROXY_CONF" >/dev/null; then
    pass
else
    fail "tinyproxy.conf lost a filter directive, gained a trailing comment, or claims case-insensitivity fnmatch cannot deliver"
fi

# Test 16b: the config is baked into the egress image, not mounted
echo -n "Test 16b: Dockerfile.egress — copies tinyproxy.conf and the entrypoint into the image... "
if grep -q '^COPY proxy/tinyproxy.conf /etc/tinyproxy/tinyproxy.conf$' "$KIT/Dockerfile.egress.example" \
    && grep -q '^COPY proxy/egress-entrypoint.sh /usr/local/bin/egress-entrypoint.sh$' "$KIT/Dockerfile.egress.example" \
    && grep -q '^USER tinyproxy$' "$KIT/Dockerfile.egress.example" \
    && ! grep -q 'tinyproxy.conf:/etc/tinyproxy' "$COMPOSE"; then
    pass
else
    fail "Dockerfile.egress no longer bakes the config in, or the compose file mounts it"
fi

# Test 17: compose puts dev on an internal network and only egress on the outside one
echo -n "Test 17: compose — devnet is internal, egress bridges both networks, dev depends on it... "
if grep -q '^  egress:$' "$COMPOSE" \
    && grep -q 'dockerfile: Dockerfile.egress' "$COMPOSE" \
    && awk '/^networks:$/{n=1} n && /^  devnet:$/{d=1} d && /internal: true/{found=1} END{exit !found}' "$COMPOSE" \
    && grep -q 'condition: service_healthy' "$COMPOSE" \
    && [ "$(grep -c '^      - egressnet$' "$COMPOSE")" -eq 1 ]; then
    pass
else
    fail "compose template lost part of the egress topology"
fi

# Test 17b: the allow-list mount cannot create a directory on the host when the file is missing
echo -n "Test 17b: compose — allow-list is a read-only long-syntax bind with create_host_path: false... "
if awk '
    /^  egress:$/ {e=1; next}
    /^  [a-z]+:$/ {e=0}
    e && /source: \.\/proxy\/allowlist\.generated\.txt$/ {src=1}
    e && /target: \/etc\/tinyproxy\/filter$/ {tgt=1}
    e && /read_only: true$/ {ro=1}
    e && /create_host_path: false$/ {chp=1}
    END {exit !(src && tgt && ro && chp)}' "$COMPOSE" \
    && ! grep -q './proxy/allowlist.generated.txt:/etc/tinyproxy/filter' "$COMPOSE"; then
    pass
else
    fail "egress allow-list mount is not a long-syntax read-only bind with create_host_path: false"
fi

# Test 17c: everything the host executes or builds from is read-only inside dev
echo -n "Test 17c: compose — scripts/, proxy/, .devcontainer/, Dockerfiles and compose file are :ro in dev... "
missing=""
for m in './scripts:/workspace/scripts:ro' './proxy:/workspace/proxy:ro' './.devcontainer:/workspace/.devcontainer:ro' \
         './docker-compose.dev.yml:/workspace/docker-compose.dev.yml:ro' './Dockerfile.dev:/workspace/Dockerfile.dev:ro' \
         './Dockerfile.egress:/workspace/Dockerfile.egress:ro'; do
    grep -qF -- "- $m" "$COMPOSE" || missing="$missing $m"
done
if [ -z "$missing" ] && grep -q '^      - .:/workspace:cached$' "$COMPOSE"; then
    pass
else
    fail "dev service is missing read-only mounts:$missing"
fi

# Test 18: compose sets both cases of the proxy variables and tunnels SSH
echo -n "Test 18: compose — upper+lower-case proxy vars, NO_PROXY bypass only, SSH tunnelled... "
# shellcheck disable=SC2016  # the ${...} below are literal compose interpolations to match
if grep -q '^      HTTP_PROXY: ' "$COMPOSE" && grep -q '^      HTTPS_PROXY: ' "$COMPOSE" \
    && grep -q '^      http_proxy: ' "$COMPOSE" && grep -q '^      https_proxy: ' "$COMPOSE" \
    && grep -q '^      NO_PROXY: ${NO_PROXY:-localhost,127.0.0.1,::1}$' "$COMPOSE" \
    && grep -q '^      no_proxy: ${NO_PROXY:-localhost,127.0.0.1,::1}$' "$COMPOSE" \
    && grep -q "nc -X connect -x \${EGRESS_PROXY_HOST:-egress}:\${EGRESS_PROXY_PORT:-3128} %h %p" "$COMPOSE"; then
    pass
else
    fail "compose template lost a proxy variable or the SSH ProxyCommand"
fi

# Test 19: the egress service never publishes a port
echo -n "Test 19: compose — egress service publishes no ports... "
if ! awk '/^  egress:$/{e=1;next} /^  [a-z]+:$/{e=0} e && /^    ports:/{found=1} END{exit found}' "$COMPOSE"; then
    fail "egress service has a ports: block"
else
    pass
fi

# Test 20: kit shell templates are syntactically valid
echo -n "Test 20: syntax — all kit shell templates pass bash -n / sh -n... "
bad=""
for f in "$KIT"/scripts/*.sh.example; do bash -n "$f" 2>/dev/null || bad="$bad $f"; done
sh -n "$ENTRYPOINT" 2>/dev/null || bad="$bad $ENTRYPOINT"
